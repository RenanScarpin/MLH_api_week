from __future__ import annotations

import argparse
import json
from pathlib import Path

from .europe_geometry import build_europe_geometry, compile_full_europe_leader_quiz
from .io_utils import write_json_atomic
from .natural_earth_client import NATURAL_EARTH_VERSION, NaturalEarthClient
from .snapshot_publish import publish_europe_snapshot

PIPELINE_DIR = Path(__file__).resolve().parents[1]
PROJECT_DIR = PIPELINE_DIR.parent
DEFAULT_LEADERS = PIPELINE_DIR / "build" / "europe-leader-states.json"
DEFAULT_OUTPUT = PIPELINE_DIR / "build" / "europe-geometry.json"
DEFAULT_CACHE = PIPELINE_DIR / "cache" / "natural-earth"
DEFAULT_FRONTEND_PUBLIC = PROJECT_DIR / "frontend" / "public"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Build real Europe map geometry from pinned Natural Earth Admin 0 "
            "Sovereignty + Map Units data and compile the full leader quiz."
        )
    )
    parser.add_argument("--leaders", type=Path, default=DEFAULT_LEADERS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE)
    parser.add_argument(
        "--natural-earth-version",
        default=NATURAL_EARTH_VERSION,
        help=(
            "Pinned Natural Earth release to use. Changing this is an intentional "
            "dataset adoption; no automatic latest-version lookup is performed."
        ),
    )
    parser.add_argument(
        "--refresh-natural-earth",
        action="store_true",
        help="Re-download files for the pinned version instead of using the versioned cache.",
    )
    parser.add_argument(
        "--publish",
        action="store_true",
        help=(
            "Publish a new immutable frontend snapshot and update latest.json only "
            "after the full quiz/map/manifest has been written successfully."
        ),
    )
    parser.add_argument("--frontend-public", type=Path, default=DEFAULT_FRONTEND_PUBLIC)
    return parser


def _print_group(title: str, rows: list[dict[str, object]]) -> None:
    print(f"{title} ({len(rows)}):")
    if not rows:
        print("  (none)")
        return
    for row in rows:
        extra = f" — {row['method']}" if row.get("method") else ""
        print(f"  - {row['displayName']} ({row['qid']}){extra}")


def main() -> int:
    args = build_parser().parse_args()
    if not args.leaders.exists():
        raise SystemExit(
            f"Missing {args.leaders}. Run `python -m geography_quiz_pipeline.build_europe_heads` first."
        )

    with args.leaders.open("r", encoding="utf-8") as file:
        leaders = json.load(file)

    stale_states = [
        state.get("displayName", state.get("qid", "unknown"))
        for state in leaders.get("states", [])
        if "geometryConstituentQids" not in state
    ]
    if stale_states:
        raise SystemExit(
            "The leader dataset was generated by an older pipeline version and lacks "
            "Natural Earth hierarchy hints. Re-run "
            "`python -m geography_quiz_pipeline.build_europe_heads` first, then run "
            "this geometry command again."
        )

    client = NaturalEarthClient(version=args.natural_earth_version)
    sovereignty = client.get_geojson(
        "sovereignty", cache_dir=args.cache_dir, refresh=args.refresh_natural_earth
    )
    map_units = client.get_geojson(
        "map_units", cache_dir=args.cache_dir, refresh=args.refresh_natural_earth
    )

    geometry = build_europe_geometry(
        leaders,
        sovereignty,
        map_units,
        natural_earth_version=args.natural_earth_version,
    )
    write_json_atomic(args.output, geometry)

    print(
        f"Wrote Europe geometry with {len(geometry['map']['features'])} Natural Earth "
        f"map-unit feature(s) to {args.output}"
    )
    fallbacks = geometry["diagnostics"]["regionalFallbacks"]
    _print_group("States using a primary-map-unit regional fallback", fallbacks)

    hierarchy = [
        row
        for row in geometry["diagnostics"]["sovereigntyResolution"]
        if row["method"] != "sovereignty_qid"
    ]
    _print_group("States whose Natural Earth sovereignty needed hierarchy resolution", hierarchy)

    if args.publish:
        quiz = compile_full_europe_leader_quiz(leaders, geometry)
        snapshot_dir = publish_europe_snapshot(
            frontend_public_dir=args.frontend_public,
            leader_dataset=leaders,
            quiz=quiz,
            map_geojson=geometry["map"],
            natural_earth_version=args.natural_earth_version,
        )
        print(
            f"Published immutable snapshot {snapshot_dir.name} with "
            f"{len(quiz['subjects'])} real leader-quiz subject(s)."
        )
        print("latest.json was updated only after the complete snapshot was written.")
        print("Commons images are still intentionally null placeholders.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
